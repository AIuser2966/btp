"""Step 8b: cross-check the 2020–2025 data twice per asset, and against the old series.

    python 08_forward_test/verify_data.py        -> prints the checks, writes verification.md

Check 1 (same asset, other funds): each primary series vs. funds NOT used to build it.
Check 2 (independent public figure): Nifty vs. published year-end closes, Gold vs. the
international price (World Bank, USD) x USD/INR (FRED), Liquid vs. RBI 91-day T-bill yields.
Check 3 (overlap Feb 2013 – Dec 2019): the new kind of source vs. the original series, to show
that switching sources in 2020 does not change what each asset is.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from sip.data import read_returns_table  # noqa: E402
from sip.forward_data import (CHECKS, FORWARD_END, FORWARD_START, PRIMARY, RAW,  # noqa: E402
                              forward_returns, fund_returns)

FR = fund_returns()
FWD = forward_returns()
YEARS = range(2020, 2026)
lines: list[str] = []


def out(s: str = "") -> None:
    print(s)
    lines.append(s)


def year_ret(r: pd.Series, y: int) -> float:
    return float((1 + r.loc[f"{y}-01":f"{y}-12"]).prod() - 1)


def ann(r: pd.Series) -> float:
    r = r.dropna()
    return float((1 + r).prod() ** (12 / len(r)) - 1)


out("# Data verification, Jan 2020 – Dec 2025\n")
out("Generated by `python 08_forward_test/verify_data.py`.\n")

# ------------------------------------------------------------------ check 1: other funds
out("## Check 1: the same asset from funds not used to build it\n")
out("| Asset | Built from | Checked against | Monthly correlation | Largest monthly gap | Gap in return per year |")
out("|---|---|---|---|---|---|")
for asset, checks in CHECKS.items():
    for c in checks:
        both = pd.concat([FWD[asset], FR[c].loc[FORWARD_START:FORWARD_END]], axis=1).dropna()
        gap = (both.iloc[:, 1] - both.iloc[:, 0])
        g_ann = ann(both.iloc[:, 1]) - ann(both.iloc[:, 0])
        out(f"| {asset} | {' + '.join(PRIMARY[asset])} | {c} ({len(both)} months) | "
            f"{both.corr().iloc[0, 1]:.4f} | {gap.abs().max():.2%} | {g_ann:+.2%} |")
out()

# ------------------------------------------------------------------ check 2: public figures
out("## Check 2: independent published figures\n")
closes = pd.read_csv(RAW / "nifty50_year_end_closes.csv", index_col="Year")["Nifty50_close"]
out("**Nifty**: index funds reinvest dividends, so each year they should beat the published "
    "price index by roughly the dividend yield (about 1–1.5%) minus fund costs.\n")
out("| Year | Nifty 50 close (published) | Price change | Our Nifty series | Difference (≈ dividends − costs) |")
out("|---|---|---|---|---|")
for y in YEARS:
    pr = closes[y] / closes[y - 1] - 1
    ours = year_ret(FWD["Nifty"], y)
    out(f"| {y} | {closes[y]:,.2f} | {pr:+.2%} | {ours:+.2%} | {ours - pr:+.2%} |")
out()

gold_usd = pd.read_csv(RAW / "gold_usd_worldbank_monthly.csv")
gold_usd.index = pd.PeriodIndex(gold_usd["Date"], freq="M")
fx = pd.read_csv(RAW / "usdinr_daily_fred_2020_2025.csv", parse_dates=["Date"]).set_index("Date")["USDINR"]
old_fx = pd.read_csv(HERE.parent / "00_raw_data" / "raw" / "usdinr_daily_fred.csv",
                     parse_dates=["Date"]).set_index("Date").iloc[:, 0]
fx_all = pd.concat([old_fx.loc[:"2019-11-30"], fx]).dropna()
fx_avg = fx_all.resample("ME").mean()
fx_avg.index = fx_avg.index.to_period("M")
intl = (gold_usd["Gold_USD_monthly_avg"] * fx_avg).dropna()
out("**Gold**: international gold (World Bank monthly average, USD) × USD/INR (FRED monthly "
    "average) against our gold ETF series. The international figure is a monthly *average*, so "
    "it lags month-end prices, and Indian gold also carries import duty, which was raised in "
    "July 2022 (≈10.75% → 15%) and cut in July 2024 (15% → 6%).\n")
out("| Year | International gold in ₹ (Dec avg → Dec avg) | Our gold series (Dec → Dec) | Difference |")
out("|---|---|---|---|")
for y in YEARS:
    i = intl[f"{y}-12"] / intl[f"{y - 1}-12"] - 1
    ours = year_ret(FWD["Gold"], y)
    out(f"| {y} | {i:+.2%} | {ours:+.2%} | {ours - i:+.2%} |")
six_i = intl["2025-12"] / intl["2019-12"]
six_o = float((1 + FWD["Gold"]).prod())
out(f"\nOver the six years: international ×{six_i:.2f}, our series ×{six_o:.2f}. "
    "The duty cut alone (1.06 / 1.125 ≈ 0.94) and ETF costs (~0.5%/yr) account for most of the gap.\n")

tb = pd.read_csv(RAW / "tbill_91d_spot_yields.csv")
out("**Liquid**: liquid funds should earn about the 91-day T-bill yield (RBI auction cut-offs), "
    "usually a little more.\n")
out("| Year | Our Liquid series | RBI 91-day T-bill yields seen that year |")
out("|---|---|---|")
for y in YEARS:
    seen = tb[tb["Auction date"].str.startswith(str(y))]
    txt = ", ".join(f"{v:.2f}% ({d})" for d, v in zip(seen["Auction date"], seen["91d T-bill yield %"])) or "—"
    out(f"| {y} | {year_ret(FWD['Liquid'], y):.2%} | {txt} |")
out()

# ------------------------------------------------------------------ check 3: overlap
out("## Check 3: new sources vs. the original series, Feb 2013 – Dec 2019\n")
out("Direct plans start in Jan 2013 (Gold BeES has its current scheme code only from 2017), so each fund is compared over the months both exist.\n")
old = read_returns_table()
ov = slice("2013-02", "2019-12")
out("| Asset | Fund | Months compared | Monthly correlation | Fund return/yr | Original series return/yr |")
out("|---|---|---|---|---|---|")
for asset, cols in PRIMARY.items():
    for c in cols:
        both = pd.concat([FR[c].loc[ov], old[asset].loc[ov]], axis=1).dropna()
        x, y = both.iloc[:, 0], both.iloc[:, 1]
        out(f"| {asset} | {c} | {both.index[0]} – {both.index[-1]} ({len(both)}) | {x.corr(y):.3f} | "
            f"{ann(x):.2%} | {ann(y):.2%} |")
out("\nNifty moves almost identically (correlation 0.999); the funds trail by ~0.3–0.5%/yr "
    "(fund costs, and actual dividends a little below the 1.3% assumed). Gold ETFs follow "
    "international gold closely (they differ by import duty changes and ETF costs). Liquid funds earn "
    "0.3–0.5%/yr more than the T-bill index, and their monthly wiggles differ (they are tiny), "
    "which is expected: funds also hold money-market paper, not only T-bills.\n")

(HERE / "verification.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\nwrote 08_forward_test/verification.md")
